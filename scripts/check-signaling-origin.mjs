import assert from 'node:assert/strict';
import http from 'node:http';
import { build } from 'esbuild';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
import fs from 'node:fs';
import { createRequire } from 'node:module';
const output = path.resolve('.cache/origin-test'); fs.mkdirSync(output,{recursive:true});
const file = path.join(output,'origin.mjs');
await build({entryPoints:['apps/desktop/electron/signaling-origin.ts'],bundle:true,platform:'node',format:'esm',outfile:file});
const {resolveSignalingOrigin} = await import(pathToFileURL(file));
const embeddedFile = path.join(output, 'embedded.cjs');
await build({ entryPoints: ['apps/desktop/electron/embedded-server.ts'], bundle: true, platform: 'node', format: 'cjs', outfile: embeddedFile });
const { EmbeddedSignalingServer } = createRequire(import.meta.url)(embeddedFile);
let validV4=false;
let validV6=true;
const v4=http.createServer((req,res)=>{res.end(JSON.stringify(validV4?{ok:true,service:'game-share-signaling'}:{Browser:'Steam DevTools'}));});
const v6=http.createServer((req,res)=>{res.end(JSON.stringify(validV6?{ok:true,service:'game-share-signaling'}:{service:'unrelated-service'}));});
const listen=(server,options)=>new Promise((resolve,reject)=>{server.once('error',reject);server.listen(options,resolve);});
try {
 await listen(v4,{host:'127.0.0.1',port:0});const port=v4.address().port;
 await listen(v6,{host:'::',port,ipv6Only:false});
 assert.equal(await resolveSignalingOrigin(port),`http://[::1]:${port}`);
 const reused = new EmbeddedSignalingServer({ port });
 const reusedStatus = await reused.start();
 assert.equal(reusedStatus.state, 'port-in-use');
 assert.equal(reusedStatus.localUrl, `http://[::1]:${port}`, 'Reused host rooms must use the verified IPv6 service');
 await reused.stop();
 assert.equal(await resolveSignalingOrigin(port), `http://[::1]:${port}`, 'Stopping a client must not stop a reused service');
 validV6=false;
 await assert.rejects(()=>resolveSignalingOrigin(port),/未找到有效/);
 const wrongService = new EmbeddedSignalingServer({ port });
 const failedStatus = await wrongService.start();
 assert.equal(failedStatus.state, 'failed');
 assert.match(failedStatus.detail, /被其他程序占用/);
 await wrongService.stop();
 validV4=true;assert.equal(await resolveSignalingOrigin(port),`http://127.0.0.1:${port}`);
 const ipv4Reuse = new EmbeddedSignalingServer({ port });
 assert.equal((await ipv4Reuse.start()).localUrl, `http://127.0.0.1:${port}`);
 await ipv4Reuse.stop();
 await new Promise(resolve=>v6.close(resolve));
 assert.equal(await resolveSignalingOrigin(port),`http://127.0.0.1:${port}`);
 console.log('PASS: conflicting IPv4 service rejected, verified IPv6 and IPv4 service reused for host rooms, unrelated services fail explicitly, reused services survive client stop');
} finally {v4.close();v6.close();}
